// Helper to get verses by category
export function getVersesByCategory(category: EmotionalCategory | "all"): NKJVVerse[] {
  if (category === "all") return LOCAL_NKJV_VERSES;
  return LOCAL_NKJV_VERSES.filter((v) => v.category === category);
}

// Helper to pick daily verse based on day of year
export function getDailyVerse(): NKJVVerse {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = (now.getTime() - startOfYear.getTime()) + ((startOfYear.getTimezoneOffset() - now.getTimezoneOffset()) * 60 * 1000);
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  return LOCAL_NKJV_VERSES[dayOfYear % LOCAL_NKJV_VERSES.length];
}

// Bolls Life API Book ID Mapping for common books
const BOOK_ID_MAP: Record<string, number> = {
  genesis: 1, exodus: 2, psalms: 19, psalm: 19, proverbs: 20, isaiah: 23,
  micah: 33, matthew: 40, romans: 45, "1corinthians": 46, "2corinthians": 47,
  galatians: 48, ephesians: 49, philippians: 50, colossians: 51,
  "1timothy": 54, "2timothy": 55, james: 59, "1peter": 60, "1john": 62
};

/**
 * Free & Keyless live fetcher using Bolls Life Bible API
 * Fallback to local array seamlessly if offline or API error
 */
export async function fetchLiveNKJVVerse(
  bookName: string,
  chapter: number,
  verse: number
): Promise<{ reference: string; text: string; source: "live_api" | "local_fallback" }> {
  const normalizedBook = bookName.toLowerCase().replace(/\s+/g, "");
  const bookId = BOOK_ID_MAP[normalizedBook] || 46; // fallback 1 Corinthians

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 3500); // 3.5s timeout for fast mobile response

    const res = await fetch(`https://bolls.life/get-verse/NKJV/${bookId}/${chapter}/${verse}/`, {
      signal: controller.signal,
      headers: { Accept: "application/json" }
    });
    clearTimeout(timeoutId);

    if (res.ok) {
      const data = await res.json();
      if (data && data.text) {
        // Strip out HTML tags if present in response
        const cleanText = data.text.replace(/<[^>]*>?/gm, "").trim();
        return {
          reference: `${bookName} ${chapter}:${verse}`,
          text: cleanText,
          source: "live_api"
        };
      }
    }
  } catch (err) {
    // Offline or network error: graceful fallback
  }

  // Fallback to local verse search
  const found = LOCAL_NKJV_VERSES.find(
    (v) => v.reference.toLowerCase().includes(bookName.toLowerCase())
  ) || LOCAL_NKJV_VERSES[0];

  return {
    reference: found.reference,
    text: found.text,
    source: "local_fallback"
  };
}
